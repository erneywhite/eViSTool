using eViSTool.Core.Mods;

namespace eViSTool.Presentation;

/// <summary>
/// Откуда взять значок мода (docs/design.md, раздел 7): иконка modicon.png из файла мода, если файл на этом диске и
/// иконка в нём есть; иначе логотип с модбазы; иначе буквы цветом мода — их рисует разметка. Одно значение, а не два:
/// строка таблицы, переиспользованная под другой мод, меняет его разом, и окно не просит логотип прежнего мода.
/// </summary>
/// <param name="File">Файл мода на этом диске; null — файла здесь нет (удалённый сервер, сервер у хостера).</param>
/// <param name="Logo">Логотип с модбазы (без её стандартной картинки); null — неизвестен или своего нет.</param>
public sealed record ModIconSource(ModFileStamp? File, string? Logo);
